fun guessCategory(name: String): String {
    for ((keys, category) in RULES) {
        for (k in keys) {
            if (name.contains(k)) return category
        }
    }
    return "其他"
}

/** 按区域兜底: 不再有「速冻」分类（存区已表达）；分类只用于筛选面板与编辑浮窗展示 */
fun guessCategoryFor(name: String, zone: StorageZone): String = guessCategory(name)
